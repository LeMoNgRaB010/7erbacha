#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*curr;

	if (!lst || !new)
		return ;
	curr = ft_lstlast(*lst);
	if (!curr)
	{
		*lst = new;
	}
	else
	{
		curr->next = new;
	}
}
